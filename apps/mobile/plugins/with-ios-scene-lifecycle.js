// Expo config plugin: adopt the UIScene lifecycle on iOS.
//
// Why this exists: building the upstream mobile app against the iOS 26/27 SDK
// produces an app that dies on launch with EXC_BREAKPOINT inside
// `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption` — those SDKs
// require every app to adopt UIScene, and the Expo prebuild template still
// creates a window-owning AppDelegate with no scene manifest and no
// SceneDelegate. This plugin performs the whole adoption at prebuild time, so
// the fix survives `expo prebuild --clean` instead of living as hand edits
// inside the gitignored `ios/` directory.
//
// It does three things:
//   1. writes `ios/<project>/SceneDelegate.swift`,
//   2. moves the React Native window setup out of AppDelegate and points the
//      app at that SceneDelegate,
//   3. registers the new file with the Xcode target and declares the scene
//      manifest in Info.plist.
//
// Every AppDelegate edit asserts on the upstream text it expects. When Expo
// changes its template the prebuild fails loudly here, which is the point:
// a silent no-op would ship another app that crashes on launch.

const fs = require("node:fs");
const path = require("node:path");
const {
  IOSConfig,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require("expo/config-plugins");

const SCENE_DELEGATE_FILENAME = "SceneDelegate.swift";

const SCENE_DELEGATE_SOURCE = `internal import Expo
import React
import ReactAppDependencyProvider
import UIKit

// Generated by plugins/with-ios-scene-lifecycle.js — edit the plugin, not this
// file: \`expo prebuild\` overwrites it.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else { return }

    let delegate = ReactNativeDelegate()
    let factory = ExpoReactNativeFactory(delegate: delegate)
    delegate.dependencyProvider = RCTAppDependencyProvider()

    reactNativeDelegate = delegate
    reactNativeFactory = factory

    let nextWindow = UIWindow(windowScene: windowScene)
    window = nextWindow

    factory.startReactNative(
      withModuleName: "main",
      in: nextWindow,
      launchOptions: nil)

    if let appDelegate = UIApplication.shared.delegate as? AppDelegate {
      appDelegate.window = nextWindow
    }
  }

  // Linking API
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let url = URLContexts.first?.url else { return }
    RCTLinkingManager.application(UIApplication.shared, open: url, options: [:])
  }

  // Universal Links
  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    RCTLinkingManager.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const SCENE_CONFIGURATION_METHOD = `
  // UIScene lifecycle (required starting with the iOS 26/27 SDKs; window setup
  // happens in SceneDelegate.scene(_:willConnectTo:options:) instead).
  public func application(
    _ application: UIApplication,
    configurationForConnecting connectingSceneSession: UISceneSession,
    options: UIScene.ConnectionOptions
  ) -> UISceneConfiguration {
    let configuration = UISceneConfiguration(
      name: "Default Configuration",
      sessionRole: connectingSceneSession.role)
    configuration.delegateClass = SceneDelegate.self
    return configuration
  }
`;

// The window setup the template puts in `didFinishLaunchingWithOptions`. It
// starts at the delegate construction and ends at the `#endif` closing the
// platform guard around `factory.startReactNative`.
const WINDOW_SETUP_START = "    let delegate = ReactNativeDelegate()";
const WINDOW_SETUP_END = "#endif\n";
const DID_FINISH_LAUNCHING_RETURN =
  "    return super.application(application, didFinishLaunchingWithOptions: launchOptions)\n  }\n";

function fail(what) {
  throw new Error(
    `[with-ios-scene-lifecycle] ${what}. The Expo AppDelegate template changed; ` +
      "update apps/mobile/plugins/with-ios-scene-lifecycle.js to match it.",
  );
}

function patchAppDelegate(contents) {
  if (contents.includes("configurationForConnecting")) return contents;

  const start = contents.indexOf(WINDOW_SETUP_START);
  if (start === -1) fail("could not find the React Native window setup");
  const end = contents.indexOf(WINDOW_SETUP_END, start);
  if (end === -1) fail("could not find the end of the window setup block");

  const withoutWindowSetup =
    contents.slice(0, start) + contents.slice(end + WINDOW_SETUP_END.length);

  const returnIndex = withoutWindowSetup.indexOf(DID_FINISH_LAUNCHING_RETURN);
  if (returnIndex === -1) fail("could not find the end of didFinishLaunching");

  const insertAt = returnIndex + DID_FINISH_LAUNCHING_RETURN.length;
  return (
    withoutWindowSetup.slice(0, insertAt) +
    SCENE_CONFIGURATION_METHOD +
    withoutWindowSetup.slice(insertAt)
  );
}

function withSceneManifest(config) {
  return withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    };
    return config;
  });
}

function withSceneDelegateFile(config) {
  return withDangerousMod(config, [
    "ios",
    (config) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(
        config.modRequest.projectRoot,
      );
      const target = path.join(
        config.modRequest.platformProjectRoot,
        projectName,
        SCENE_DELEGATE_FILENAME,
      );
      fs.writeFileSync(target, SCENE_DELEGATE_SOURCE, "utf8");
      return config;
    },
  ]);
}

function withPatchedAppDelegate(config) {
  return withDangerousMod(config, [
    "ios",
    (config) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(
        config.modRequest.projectRoot,
      );
      const appDelegate = path.join(
        config.modRequest.platformProjectRoot,
        projectName,
        "AppDelegate.swift",
      );
      const contents = fs.readFileSync(appDelegate, "utf8");
      fs.writeFileSync(appDelegate, patchAppDelegate(contents), "utf8");
      return config;
    },
  ]);
}

// The pbxproj still uses plain groups (objectVersion 54), so a new source file
// has to be registered explicitly — dropping it in the folder is not enough.
function withSceneDelegateInTarget(config) {
  return withXcodeProject(config, (config) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(
      config.modRequest.projectRoot,
    );
    const filepath = `${projectName}/${SCENE_DELEGATE_FILENAME}`;
    if (!config.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: config.modResults,
      });
    }
    return config;
  });
}

module.exports = function withIosSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withSceneDelegateFile(config);
  config = withPatchedAppDelegate(config);
  config = withSceneDelegateInTarget(config);
  return config;
};

module.exports.patchAppDelegate = patchAppDelegate;
